#!/usr/bin/env node
// Builds the page's Tailwind CSS ahead of time and writes it into web/index.html between the two tailwind markers.
// (The page used to download Tailwind's whole compiler at every load from cdn.tailwindcss.com and build this in the browser.)
//
//   node scripts/build-css.mjs           rewrite the block in web/index.html
//   node scripts/build-css.mjs --check   exit 1 if the block in web/index.html is not what a fresh build gives
//   node scripts/build-css.mjs --extra <file-with-class-names>   also build the classes listed in that file (used by the screenshot check)
//
// Needs `npm install` (tailwindcss is pinned to an exact version in package.json).
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const page = join(root, 'web/index.html');
const START = '<!-- tailwind:start (generated by scripts/build-css.mjs: do not edit by hand) -->';
const END = '<!-- tailwind:end -->';

export function buildCss(html, extraClasses = '') {
  const a = html.indexOf(START), b = html.indexOf(END);
  const source = a >= 0 && b > a ? html.slice(0, a) + html.slice(b + END.length) : html;   // never scan the generated CSS itself
  const dir = mkdtempSync(join(tmpdir(), 'twbuild-'));
  const content = join(dir, 'content.html'), input = join(dir, 'in.css'), out = join(dir, 'out.css');
  writeFileSync(content, source + '\n' + extraClasses);
  writeFileSync(input, '@tailwind base;\n@tailwind components;\n@tailwind utilities;\n');
  execFileSync(join(root, 'node_modules/.bin/tailwindcss'), ['-c', join(root, 'tailwind.config.cjs'), '--content', content, '-i', input, '-o', out, '--minify'], { stdio: ['ignore', 'ignore', 'pipe'] });
  return readFileSync(out, 'utf8').trim();
}

export function withBlock(html, css) {
  const block = `${START}\n  <style>${css}</style>\n  ${END}`;
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a >= 0 && b > a) return html.slice(0, a) + block + html.slice(b + END.length);
  throw new Error('markers not found in web/index.html');
}

if (process.argv[1] && process.argv[1].endsWith('build-css.mjs')) {
  const html = readFileSync(page, 'utf8');
  const i = process.argv.indexOf('--extra');
  const extra = i > 0 ? readFileSync(process.argv[i + 1], 'utf8') : '';
  const next = withBlock(html, buildCss(html, extra));
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('web/index.html: the Tailwind block is out of date. Run: node scripts/build-css.mjs'); process.exit(1); }
    console.log('Tailwind block is up to date');
  } else { writeFileSync(page, next); console.log(`wrote ${Buffer.byteLength(next)} bytes (CSS ${Buffer.byteLength(buildCss(next))} bytes)`); }
}
